export type SampleRepo = {
  id: number;
  fullName: string;
  description: string;
  language: string | null;
  topics: string[];
  license: string | null;
  createdAt: string;
  forks: number;
  openIssues: number;
  demo?: boolean;
  stars: Partial<Record<(typeof SAMPLE_DATES)[number], number>>;
};

function track(start: number, deltas: number[]): SampleRepo["stars"] {
  const stars: SampleRepo["stars"] = { [SAMPLE_DATES[0]]: start };
  let value = start;
  deltas.forEach((delta, index) => {
    value += delta;
    const date = SAMPLE_DATES[index + 1];
    if (date) stars[date] = value;
  });
  return stars;
}

